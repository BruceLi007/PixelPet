"""
================================================================================
键盘输入处理模块 - 检测和响应用户的键盘操作
================================================================================

【文件作用】
    本文件是控制器层（Controller）的核心组件，负责处理所有键盘输入：
    - 检测用户按下了哪些方向键（↑↓←→ 或 WASD）
    - 支持多键同时按下，实现斜向移动
    - 计算移动方向和速度（包含斜向速度归一化）
    - 提供按键状态查询接口

【使用技术】
    - PyQt6.QtCore.QObject：Qt 的对象基类，所有 Qt 对象都继承自它
    - PyQt6.QtCore.Qt：包含 Qt 常量，如键码（Key_Up, Key_Down 等）
    - PyQt6.QtGui.QKeyEvent：Qt 键盘事件类，包含按键信息
    - Python set（集合）：存储当前按下的按键，用于多键检测

【核心概念 - 多键斜向移动】
    1. 使用 set 存储按下的按键：快速添加、删除、查询
    2. 每帧检测多个按键：同时检测上下、左右键
    3. 斜向速度归一化：防止斜向移动速度过快

【斜向速度归一化原理】
    如果同时按左右和上下方向键，角色应该沿45度方向移动：
    - 假设单键速度是 V
    - 斜向时 x 和 y 分量都是 V
    - 实际速度 = √(V² + V²) = V × √2 ≈ 1.414V
    - 为了让斜向速度和直线速度一致，需要归一化
    - 归一化系数 = 1/√2 ≈ 0.707
    - 斜向速度 = V × 0.707 × √2 = V

【依赖关系】
    被导入：main.py
    导入：config.settings（获取移动速度配置）

================================================================================
"""

# ================================================================================
# 导入 PyQt6 组件
# ================================================================================

from PyQt6.QtCore import QObject, Qt
# QObject：Qt 所有对象的基类
#   - 提供了信号槽机制的对象需要继承它
#   - InputHandler 需要发送信号时继承自 QObject

from PyQt6.QtGui import QKeyEvent
# QKeyEvent：键盘事件类


# ================================================================================
# 导入项目配置模块
# ================================================================================

from config.settings import MOVE_SPEED
# 从配置模块导入：
#   - MOVE_SPEED：每帧移动的像素数（如 5）

from features.speed_boost import SpeedBoostHandler
# 双击加速处理器


# ================================================================================
# 键盘输入处理器类
# ================================================================================

class InputHandler(QObject):
    """
    键盘输入处理器类

    负责检测和响应用户的键盘输入：

    主要功能：
        1. 跟踪当前按下的所有按键（使用 set）
        2. 处理按键按下事件（keyPressEvent）
        3. 处理按键释放事件（keyReleaseEvent）
        4. 计算移动方向和速度（handle_input）

    技术特点：
        - 继承自 QObject（保留用于信号槽扩展）
        - 使用 set 存储按键（O(1) 查找效率高）
        - 支持多键同时检测（斜向移动的基础）

    使用方式：
        handler = InputHandler()           # 创建处理器
        handler.keyPressEvent(event)       # 按键按下时调用
        handler.keyReleaseEvent(event)      # 按键释放时调用
        dx, dy = handler.handle_input()     # 每帧调用获取移动量
    """

    # ==========================================================================
    # 类常量 - 速度归一化系数
    # ==========================================================================

    # 斜向移动时的速度归一化系数
    # 原理：如果 x 和 y 方向同时有输入（斜向），
    #       实际速度会是单方向的 √2 倍
    #       乘以 1/√2 ≈ 0.707 可以让速度保持一致
    NORMALIZE_FACTOR = 0.707  # 1/√2

    # 为什么是 0.707？
    # 如果单方向速度是 5，斜向时：
    #   - 未归一化：速度 = √(5² + 5²) = 7.07
    #   - 归一化后：速度 = 5 × 0.707 × √2 = 5

    # ==========================================================================
    # 初始化 - 创建输入处理器
    # ==========================================================================

    def __init__(self):
        """
        构造函数 - 初始化输入处理器
        """

        super().__init__()
        # 调用父类 QObject 的构造函数
        # 这是 Python 类的标准做法，确保对象正确初始化

        self.keys_pressed = set()
        # keys_pressed：存储当前按下的键的集合
        #
        # 为什么用 set 而不是 list？
        # - set 的 add()、discard()、in 操作都是 O(1)
        # - list 的 append()、remove()、in 操作是 O(n)
        # - 按键检测需要频繁的添加、删除、查询，set 更高效
        #
        # 集合元素：Qt.Key_XXX 常量（如 Qt.Key.Key_Up）
        # 示例：{Qt.Key.Key_Up, Qt.Key.Key_Right} 表示同时按了上和右


        # --------------------------------------------------------------------------
        # 双击加速处理器
        # --------------------------------------------------------------------------

        self.speed_boost_handler = SpeedBoostHandler()
        # speed_boost_handler：双击加速处理器


    # ==========================================================================
    # 事件处理方法 - 由 Qt 事件系统调用
    # ==========================================================================

    def keyPressEvent(self, event: QKeyEvent):
        """
        处理按键按下事件

        参数：
            event (QKeyEvent)：Qt 键盘事件对象

        实现：
            1. 从事件对象获取按键码
            2. 将按键码添加到 keys_pressed 集合
            3. 检测双击加速（0.5秒内同一键再次按下）

        调用时机：
            用户按下键盘上的任意键时，Qt 自动调用此方法
        """

        key = event.key()
        # event.key()：获取按键的 Qt 键码
        # 返回值是 Qt.Key_XXX 常量
        # 例如：Qt.Key.Key_Up 表示上方向键


        # --------------------------------------------------------------------------
        # 双击加速检测
        # --------------------------------------------------------------------------

        self.speed_boost_handler.check_double_tap(key, event.isAutoRepeat())


        self.keys_pressed.add(key)
        # set.add()：将元素添加到集合
        # 如果元素已存在，不会有任何效果
        # 添加到集合表示"这个键当前被按下"


    def keyReleaseEvent(self, event: QKeyEvent):
        """
        处理按键释放事件

        参数：
            event (QKeyEvent)：Qt 键盘事件对象

        实现：
            1. 从事件对象获取按键码
            2. 将按键码从 keys_pressed 集合中移除
            3. 如果释放的是带有加速的键，重置加速

        调用时机：
            用户释放键盘上的任意键时，Qt 自动调用此方法

        重要性：
            如果不及时释放，角色会一直移动
            这也是为什么用 set 而不是计数
        """

        key = event.key()
        # event.key()：获取释放的键的 Qt 键码

        self.keys_pressed.discard(key)
        # set.discard()：从集合中移除元素
        # 如果元素不存在，不会有任何效果（不会抛出异常）
        # 移除出集合表示"这个键已经被释放"


        # --------------------------------------------------------------------------
        # 重置加速
        # --------------------------------------------------------------------------

        self.speed_boost_handler.reset_if_no_direction_keys(self.keys_pressed, key)


    # ==========================================================================
    # 核心方法 - 计算移动方向和速度
    # ==========================================================================

    def handle_input(self) -> tuple:
        """
        处理输入并计算移动方向和速度

        返回：
            tuple：(dx, dy)
                   dx：x 方向移动量（正数=右，负数=左）
                   dy：y 方向移动量（正数=下，负数=上）

        实现逻辑：

            1. 初始化移动分量为 0
            2. 检测每个方向键是否被按下
            3. 如果按下，累加对应的移动分量
            4. 如果斜向（dx≠0 且 dy≠0），应用归一化系数
            5. 乘以基础速度得到最终移动量

        方向键映射：
            ← 或 A → dx -= 1（向左）
            → 或 D → dx += 1（向右）
            ↑ 或 W → dy -= 1（向上）
            ↓ 或 S → dy += 1（向下）

        使用方式：
            dx, dy = handler.handle_input()
            if dx != 0 or dy != 0:
                pet.move(dx, dy)

        注意：
            此方法每帧都会被调用（通过主循环的定时器）
            调用频率由 MOVE_INTERVAL 控制（默认 60 FPS）
        """

        # --------------------------------------------------------------------------
        # 步骤1：初始化移动分量
        # --------------------------------------------------------------------------

        dx = 0.0
        # dx：水平方向移动量
        # 正数表示向右，负数表示向左，0 表示不水平移动

        dy = 0.0
        # dy：垂直方向移动量
        # 正数表示向下，负数表示向上，0 表示不垂直移动


        # --------------------------------------------------------------------------
        # 步骤2：检测方向键
        # --------------------------------------------------------------------------

        # 检测上方向键（↑ 或 W）
        # Qt.Key.Key_Up：键盘的上箭头键
        # Qt.Key.Key_W：键盘的 W 键（游戏常用 WASD 控制）
        if Qt.Key.Key_Up in self.keys_pressed or Qt.Key.Key_W in self.keys_pressed:
            dy -= 1
            # dy -= 1：向上移动
            # 注意：屏幕坐标系 y 轴向下为正，所以向上是 dy -= 1


        # 检测下方向键（↓ 或 S）
        if Qt.Key.Key_Down in self.keys_pressed or Qt.Key.Key_S in self.keys_pressed:
            dy += 1
            # dy += 1：向下移动


        # 检测左方向键（← 或 A）
        if Qt.Key.Key_Left in self.keys_pressed or Qt.Key.Key_A in self.keys_pressed:
            dx -= 1
            # dx -= 1：向左移动


        # 检测右方向键（→ 或 D）
        if Qt.Key.Key_Right in self.keys_pressed or Qt.Key.Key_D in self.keys_pressed:
            dx += 1
            # dx += 1：向右移动


        # --------------------------------------------------------------------------
        # 步骤3：斜向移动速度归一化
        # --------------------------------------------------------------------------

        # 判断是否为斜向移动：水平方向和垂直方向同时有输入
        # 例如：同时按 ↑ 和 ← 会得到 dx=-1, dy=-1（斜向左上）
        if dx != 0 and dy != 0:
            # 如果是斜向移动，应用归一化系数

            dx *= self.NORMALIZE_FACTOR
            # 水平速度乘以 0.707

            dy *= self.NORMALIZE_FACTOR
            # 垂直速度乘以 0.707


        # --------------------------------------------------------------------------
        # 步骤4：应用基础速度和加速
        # --------------------------------------------------------------------------

        # 将方向分量乘以基础速度得到最终移动像素数
        dx *= MOVE_SPEED * self.speed_boost_handler.get_boost()
        # 例如：dx=1（向右），MOVE_SPEED=5 → dx=5.0（向右移动5像素）

        dy *= MOVE_SPEED * self.speed_boost_handler.get_boost()
        # 例如：dy=-1（向上），MOVE_SPEED=5 → dy=-5.0（向上移动5像素）


        # --------------------------------------------------------------------------
        # 返回移动量元组
        # --------------------------------------------------------------------------

        return (dx, dy)
        # 返回格式：(水平移动量, 垂直移动量)
        # 单位：像素/帧（每帧移动这么多像素）


    # ==========================================================================
    # 辅助方法
    # ==========================================================================

    def is_moving(self) -> bool:
        """
        检查是否有任何方向键被按下

        返回：
            bool：True 表示有键被按下，False 表示没有

        实现：
            调用 handle_input() 获取移动量
            如果 dx 或 dy 不为 0，说明有键被按下

        备注：
            此方法当前版本未使用
            保留用于未来扩展（如检测是否在移动）
        """

        dx, dy = self.handle_input()
        # 获取当前移动量

        return dx != 0 or dy != 0
        # 如果任一方向有移动量，返回 True


    def is_escape_pressed(self) -> bool:
        """
        检查 ESC 键是否被按下

        返回：
            bool：True 表示 ESC 被按下，False 表示没有

        用途：
            用于退出鼠标跟随模式等需要 ESC 快捷键的场景
        """

        return Qt.Key.Key_Escape in self.keys_pressed


    def clear(self):
        """
        清空所有按下的键状态

        实现：
            调用 set.clear() 清空集合

        用途：
            程序退出时调用
            避免程序关闭后按键状态残留导致问题

        注意：
            一般不需要主动调用
            因为按键释放事件会自动更新集合
        """

        self.keys_pressed.clear()
        # set.clear()：移除集合中的所有元素
        # 清空后相当于所有键都被释放了

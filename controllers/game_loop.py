"""
================================================================================
游戏循环控制器 - 管理游戏逻辑更新和穿墙边界处理
================================================================================

【文件作用】
    本文件是控制器层（Controller）的另一个核心组件，负责游戏逻辑：
    - 穿墙循环逻辑：当角色移出屏幕边界时，从对侧重新进入
    - 封装更新和渲染接口，供主循环调用
    - 协调 PixelPet 和 MainWindow 之间的数据流动

【使用技术】
    - Python 类组合：通过组合而非继承使用 PixelPet 和 MainWindow
    - 坐标数学计算：处理穿墙边界的数学逻辑

【穿墙循环原理】
    当角色的任意部分完全移出屏幕时，从对侧重新进入：

    水平方向（左/右穿墙）：
    ┌─────────────────────────────────────────┐
    │ 角色   →→→                    ←←← 角色   │
    │ 向右移出 ──────────────────→ 从左边回来  │
    │ 向左移出 ←─────────────────→ 从右边回来  │
    └─────────────────────────────────────────┘

    垂直方向（上/下穿墙）：
    ┌─────────────────────────────────────────┐
    │ 角色   ↓↓↓                    ↑↑↑ 角色   │
    │ 向下移出 ──────────────────→ 从上边回来  │
    │ 向上移出 ──────────────────→ 从下边回来  │
    └─────────────────────────────────────────┘

【边界计算逻辑】
    判断角色是否"完全"移出屏幕：
    - 左边界：x < -pet_width      （角色最左点在屏幕最左边之左）
    - 右边界：x > screen_width     （角色最左点在屏幕最右边之右）
    - 上边界：y < -pet_height     （角色最上点在屏幕上边框之上）
    - 下边界：y > screen_height   （角色最上点在屏幕下边框之下）

    注意：判断的是角色左上角的位置，不是中心点
          这样设计是为了"完全消失再出现"的效果

【依赖关系】
    被导入：main.py
    导入：models.pixel_pet（PixelPet 类）

================================================================================
"""

# ================================================================================
# 导入项目模块
# ================================================================================

from models.pixel_pet import PixelPet
# PixelPet：像素小人数据模型类
#   - 提供 get_position() 获取位置
#   - 提供 set_position() 设置位置
#   - 提供 get_size() 获取尺寸
# 游戏循环需要 PixelPet 来：
#   - 读取当前位置用于穿墙计算
#   - 写入新位置实现穿墙效果


# ================================================================================
# 游戏循环控制器类
# ================================================================================

class GameLoop:
    """
    游戏循环控制器类

    负责游戏的核心逻辑：

    主要职责：
        1. 管理角色位置（通过调用 PixelPet 的方法）
        2. 实现穿墙循环逻辑
        3. 提供统一的 update/render 接口

    设计模式：
        使用组合模式，将 PixelPet 和 MainWindow 作为成员变量
        而不是继承，这样更灵活且符合 MVC/MVP 架构

    使用方式：
        game_loop = GameLoop(window, pet, handler)  # 创建
        game_loop.wrap_position()                   # 更新位置（穿墙）
        game_loop.render()                          # 渲染画面

    注意：
        当前版本中，穿墙逻辑在 main.py 的定时器回调中直接调用
        update() 方法保留但未被使用
    """

    # ==========================================================================
    # 初始化
    # ==========================================================================

    def __init__(self, window, pet: PixelPet, input_handler):
        """
        构造函数 - 初始化游戏循环

        参数：
            window：MainWindow 实例，用于获取屏幕尺寸
            pet (PixelPet)：像素小人实例，用于读取/写入位置
            input_handler：InputHandler 实例（当前版本未使用）

        初始化流程：
            1. 保存窗口引用（用于获取屏幕尺寸）
            2. 保存角色引用（用于读写位置）
            3. 保存输入处理器引用（备用）
            4. 初始化运行状态标志
        """

        self.window = window
        # window：MainWindow 实例的引用
        # 用于调用 get_screen_size() 获取屏幕尺寸
        # 用于调用 get_pet_size() 获取宠物尺寸

        self.pet = pet
        # pet：PixelPet 实例的引用
        # 用于调用 get_position() 获取当前位置
        # 用于调用 set_position() 设置新位置

        self.input_handler = input_handler
        # input_handler：InputHandler 实例的引用
        # 当前版本未使用，保留用于未来扩展
        # 未来可能用于：检测特定按键组合触发特殊效果

        self.running = False
        # running：运行状态标志
        # 当前版本未使用，保留用于控制游戏暂停/继续


    # ==========================================================================
    # 游戏状态更新方法（当前版本未使用）
    # ==========================================================================

    def update(self):
        """
        更新游戏状态

        【当前版本未使用】

        原本设计用于：
            1. 处理输入（从 InputHandler 读取按键状态）
            2. 更新角色位置
            3. 应用穿墙逻辑
            4. 渲染画面

        当前实现方式：
            所有逻辑都在 main.py 的定时器回调中直接实现
            这样更直接，避免额外的方法调用开销

        保留原因：
            - 代码更清晰，便于理解流程
            - 保留扩展性，未来可以将逻辑移到此方法
        """

        # 处理输入
        dx, dy = self.input_handler.handle_input()

        # 如果有移动输入
        if dx != 0 or dy != 0:

            # 设置精灵方向
            self.pet.set_direction(dx, dy)

            # 移动
            self.pet.move(dx, dy)

            # 穿墙循环
            self.wrap_position()

            # 更新显示
            self.render()


    # ==========================================================================
    # 核心方法 - 穿墙循环
    # ==========================================================================

    def wrap_position(self):
        """
        实现穿墙循环逻辑

        【核心算法】

        当角色的左上角坐标超出屏幕边界时，
        将角色移动到对侧边缘之外，使其"穿墙"进入

        判断条件：角色的左上角完全移出屏幕

        水平方向（左右穿墙）：
        ┌──────────────────────────────────────────────────────┐
        │ 屏幕 x=0                              x=屏幕宽度     │
        │    │                                      │         │
        │    │    ┌─────┐                    ┌─────┐ │         │
        │    │    │角色 │ ←←←←←←←←←←←←←←←←← │角色 │ │         │
        │    │    └─────┘                    └─────┘ │         │
        │    │                                      │         │
        │ ←──┼──────────────────────────────────────┼─────────→
        │    │                 屏幕区域              │
        │ x<0                    ←                 x>宽度    │
        │ 左穿墙：x < -pet_width                   右穿墙：x > 宽度  │
        └──────────────────────────────────────────────────────┘

        垂直方向（上下穿墙）：
        类似水平方向，只是 y 坐标和屏幕高度

        实现步骤：
            1. 获取屏幕尺寸和宠物尺寸
            2. 获取宠物当前位置
            3. 检查是否超出每个边界
            4. 如果超出，设置新位置到对侧
        """

        # --------------------------------------------------------------------------
        # 获取屏幕尺寸
        # --------------------------------------------------------------------------

        screen_width, screen_height = self.window.get_screen_size()
        # get_screen_size() 返回 (宽度, 高度)
        # 例如：(1920, 1080) 表示屏幕宽1920像素，高1080像素

        # --------------------------------------------------------------------------
        # 获取宠物尺寸
        # --------------------------------------------------------------------------

        pet_width, pet_height = self.window.get_pet_size()
        # get_pet_size() 返回 (宽度, 高度)
        # 尺寸来自 QLabel，由 PNG 图片决定

        # --------------------------------------------------------------------------
        # 获取宠物当前位置
        # --------------------------------------------------------------------------

        x, y = self.pet.get_position()
        # get_position() 返回宠物的左上角坐标 (x, y)

        # --------------------------------------------------------------------------
        # 水平方向穿墙（左/右边界）
        # --------------------------------------------------------------------------

        # 检查左边界穿墙
        # 如果角色左上角 x 坐标小于 -宠物宽度
        # 说明角色完全移出左边界
        if x < -pet_width:
            # 将角色移动到右边界之外
            x = screen_width
            # 新 x = 屏幕宽度，这样角色从右边完全消失时开始出现

        # 检查右边界穿墙
        # 如果角色左上角 x 坐标大于屏幕宽度
        # 说明角色完全移出右边界
        elif x > screen_width:
            # 将角色移动到左边界之外
            x = -pet_width
            # 新 x = -宠物宽度，这样角色从左边完全消失时开始出现

        # --------------------------------------------------------------------------
        # 垂直方向穿墙（上/下边界）
        # --------------------------------------------------------------------------

        # 检查上边界穿墙
        # 如果角色左上角 y 坐标小于 -宠物高度
        # 说明角色完全移出上边界
        if y < -pet_height:
            # 将角色移动到下边界之外
            y = screen_height
            # 新 y = 屏幕高度，这样角色从下边完全消失时开始出现

        # 检查下边界穿墙
        # 如果角色左上角 y 坐标大于屏幕高度
        # 说明角色完全移出下边界
        elif y > screen_height:
            # 将角色移动到上边界之外
            y = -pet_height
            # 新 y = -宠物高度，这样角色从上边完全消失时开始出现

        # --------------------------------------------------------------------------
        # 保存穿墙后的新位置
        # --------------------------------------------------------------------------

        self.pet.set_position(int(x), int(y))
        # set_position()：更新宠物的位置
        # int() 转换确保坐标是整数（像素坐标不能是小数）


    # ==========================================================================
    # 渲染方法（当前版本未使用）
    # ==========================================================================

    def render(self):
        """
        渲染画面

        【当前版本未使用】

        原本设计用于：
            1. 清空屏幕背景
            2. 在新位置绘制宠物
            3. 更新显示

        当前实现方式：
            渲染逻辑在 main.py 的定时器回调中直接实现
            这样更直接，避免额外的方法调用开销

        保留原因：
            保留扩展性，未来可能需要更复杂的渲染逻辑
        """

        # 更新宠物精灵图
        # 调用 MainWindow 的方法设置当前帧图片
        self.window.set_pet_pixmap(self.pet.current_sprite)

        # 更新宠物位置
        # 调用 MainWindow 的方法移动 QLabel
        self.window.set_pet_position(self.pet.x, self.pet.y)

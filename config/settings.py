"""
================================================================================
配置文件 - 存放所有可配置的常量参数
================================================================================

【文件作用】
    本文件集中管理整个项目的所有配置参数，包括：
    - 路径配置（支持源码运行和 PyInstaller 打包后的运行）
    - 移动速度参数
    - 动画帧率参数
    - 资源文件路径

【使用技术】
    - os 模块：用于处理文件系统路径，实现跨平台路径兼容
    - sys 模块：用于检测程序是否被 PyInstaller 打包
    - 路径拼接：使用 os.path.join() 确保不同操作系统的路径分隔符兼容

【依赖关系】
    本文件不依赖其他自定义模块，但会被所有模块导入使用
    被导入：main.py, models/pixel_pet.py, views/main_window.py, controllers/*

================================================================================
"""

# ================================================================================
# 导入标准库模块
# ================================================================================

import os
# os 模块：提供操作系统相关的功能，如路径操作、文件目录操作等

import sys
# sys 模块：提供 Python 解释器相关的功能
# 主要用于检测程序运行环境（源码运行 或 打包后的 exe 运行）


# ================================================================================
# 路径配置 - 支持源码运行和 PyInstaller 打包后运行
# ================================================================================

# 获取当前文件(config/settings.py)的绝对路径
# os.path.abspath(__file__) 获取 config/settings.py 的完整路径
# 例如：'C:/project/DeskTopMan/DeskTopMan/config/settings.py'
# os.path.dirname() 获取上级目录，调用两次得到项目根目录
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# BASE_DIR = 'C:/project/DeskTopMan/DeskTopMan'（项目根目录）


# ------------------------------------------------------------------------------
# 检测运行环境，决定资源文件的根路径
# ------------------------------------------------------------------------------

# getattr(sys, 'frozen', False)：
#   - 如果程序是通过 PyInstaller 打包成 exe 运行的，sys.frozen 为 True
#   - 如果程序是直接通过 python 源码运行的，sys.frozen 不存在，默认为 False

# sys._MEIPASS：
#   - PyInstaller 打包后的临时目录，存放所有打包的资源文件
#   - 例如：'C:/Users/用户名/AppData/Local/Temp/_MEI123456/'

if getattr(sys, 'frozen', False):
    # --------------------------------------------------------------------------
    # 【打包后的运行】从 PyInstaller 的临时目录读取资源
    # --------------------------------------------------------------------------
    # 程序作为 exe 运行时，资源文件被解压到 sys._MEIPASS 目录
    # 例如：exe 同目录下有个 assets 文件夹，但实际运行时资源在临时目录
    APP_DIR = sys._MEIPASS

else:
    # --------------------------------------------------------------------------
    # 【源码运行】从项目根目录读取资源
    # --------------------------------------------------------------------------
    # 开发时直接用 python 运行源码，资源就在项目根目录的 assets 文件夹
    APP_DIR = BASE_DIR


# ================================================================================
# 移动速度配置 - 控制角色的移动速度
# ================================================================================

MOVE_SPEED = 5
# 角色每帧移动的像素数量
# 值越大移动越快，建议范围 1-10
# 当前设置：每帧移动 5 个像素

FPS = 60
# 游戏循环的帧率（Frames Per Second）
# 控制屏幕每秒刷新的次数，影响移动流畅度
# 60 FPS 表示每秒更新 60 次

MOVE_INTERVAL = 1000 // FPS
# 移动更新的时间间隔（毫秒）
# 1000 // 60 ≈ 16.67ms，每约 16.67ms 更新一次位置
# 使用整数除法 // 确保结果是整数


# ================================================================================
# 动画帧率配置 - 控制角色动画的播放速度
# ================================================================================

ANIM_FPS = 10
# 动画帧率：每秒播放的帧数
# 动画不需要像移动那样频繁更新，通常 8-15 FPS 足够
# 当前设置：每秒播放 10 帧动画

ANIM_INTERVAL = 1000 // ANIM_FPS
# 动画帧切换的时间间隔（毫秒）
# 1000 // 10 = 100ms，每 100ms 切换到下一帧动画


# ================================================================================
# 资源文件路径配置 - 指向动画帧图片的位置
# ================================================================================

# 资源根目录路径（整合打包和源码两种运行方式的路径）
SPRITE_PATH = os.path.join(APP_DIR, "assets")
# os.path.join()：智能拼接路径，自动处理不同操作系统的分隔符
# 结果示例：
#   - 源码运行：'C:/project/DeskTopMan/DeskTopMan/assets'
#   - 打包运行：'C:/Users/.../Temp/_MEI123456/assets'


# ------------------------------------------------------------------------------
# 各方向动画帧的目录路径
# ------------------------------------------------------------------------------

# 静止动画帧目录（站立待机时的动画）
# 目录下应包含 4 张图片：stay-1.png, stay-2.png, stay-3.png, stay-4.png
ANIM_STAY_PATH = os.path.join(SPRITE_PATH, "stay")

# 向左移动动画帧目录
# 目录下应包含 4 张图片：left-1.png, left-2.png, left-3.png, left-4.png
ANIM_LEFT_PATH = os.path.join(SPRITE_PATH, "left")

# 向右移动动画帧目录
# 目录下应包含 4 张图片：right-1.png, right-2.png, right-3.png, right-4.png
ANIM_RIGHT_PATH = os.path.join(SPRITE_PATH, "right")


# ================================================================================
# 透明色配置（备用）
# ================================================================================
# 注意：当前代码已改用 PNG 自带的 Alpha 通道实现透明
# 此配置保留用于可能的扩展或其他透明需求

TRANSPARENT_COLOR = (255, 0, 255)
# 洋红色 RGB 值
# 某些情况下需要将图片中的特定颜色设为完全透明
# RGB (255, 0, 255) = 纯洋红色
